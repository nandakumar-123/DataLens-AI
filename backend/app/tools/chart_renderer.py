import io
from typing import Dict, Any, List, Optional
import matplotlib
matplotlib.use('Agg')  # Run in headless mode (must be set before pyplot import)
import matplotlib.pyplot as plt
import seaborn as sns


def render_chart_to_bytes(chart: Dict[str, Any]) -> Optional[io.BytesIO]:
    """
    Takes a chart dictionary generated by Agent 8 and renders it 
    as a PNG image in memory using matplotlib/seaborn.
    """
    data = chart.get("data", [])
    if not data:
        return None

    plt.figure(figsize=(8, 4))
    try:
        sns.set_theme(style="whitegrid")
        
        chart_type = chart.get("type")
        title = chart.get("title", "")
        x_col = chart.get("x_axis")
        y_col = chart.get("y_axis")
        
        x_vals = [d.get(x_col) for d in data]
        y_vals = [d.get(y_col) for d in data]
        
        if chart_type == "line":
            sns.lineplot(x=x_vals, y=y_vals, marker="o", color="#4f46e5")
            plt.xticks(rotation=45)
        
        elif chart_type == "bar":
            # For bar charts we used horizontal layout in frontend
            sns.barplot(x=y_vals, y=x_vals, color="#8b5cf6")
            
        elif chart_type == "scatter":
            sns.scatterplot(x=x_vals, y=y_vals, color="#ec4899", alpha=0.7)
        
        else:
            # Fallback
            sns.lineplot(x=x_vals, y=y_vals, color="#333333")
            
        plt.title(title, fontsize=14, fontweight="bold", pad=15)
        plt.xlabel(x_col, fontsize=11)
        plt.ylabel(y_col, fontsize=11)
        
        plt.tight_layout()
        
        buf = io.BytesIO()
        plt.savefig(buf, format="png", dpi=150)
        buf.seek(0)
        return buf
    finally:
        plt.close()

